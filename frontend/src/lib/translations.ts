const lowerCaseMapTranslations: Record<string, string> = {};
const normalizedMapTranslations: Record<string, string> = {};

for (const [key, value] of Object.entries(mapTranslations)) {
  lowerCaseMapTranslations[key.toLowerCase()] = value;
  const normKey = key.toLowerCase().replace(/[\s_\-']/g, "");
  normalizedMapTranslations[normKey] = value;
}

export function translateMap(mapName: string): string {
  if (!mapName) return "";
  
  // gachi_ 接頭辞のストリップ
  let cleanName = mapName.trim();
  if (cleanName.startsWith("gachi_")) {
    cleanName = cleanName.substring(6).trim();
  }
  
  // 完全一致
  if (mapTranslations[cleanName]) return mapTranslations[cleanName];
  
  // 小文字一致
  const lowerName = cleanName.toLowerCase();
  if (lowerCaseMapTranslations[lowerName]) return lowerCaseMapTranslations[lowerName];
  
  // 記号・スペース除去正規化一致
  const normKey = lowerName.replace(/[\s_\-']/g, "");
  if (normalizedMapTranslations[normKey]) return normalizedMapTranslations[normKey];
  
  return cleanName;
}

